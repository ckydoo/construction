/* Sample-data default QA. Creates two throwaway workspaces through the real
 * registration/onboarding API: one with the wizard default (no loadDemo field),
 * one with an explicit opt-in. Verifies the default workspace is empty, opt-in
 * still seeds, and both open Billing after onboarding. Cleanup SQL is written
 * for the Supabase connector; no live payment is made. */
import 'dotenv/config';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createClient } from '@supabase/supabase-js';

const BASE = (process.env.QA_BASE || 'http://127.0.0.1:3000').replace(/\/$/, '');
const URL = (process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL || '').trim();
const SERVICE = (process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_SECRET_KEY || '').trim();
if (!URL || !SERVICE) throw new Error('Supabase URL and service-role key are required');
const admin = createClient(URL, SERVICE, {
  auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false },
});
const stamp = `${Date.now().toString(36)}${Math.random().toString(36).slice(2, 6)}`;
const cases = [
  { label: 'default', email: `qa-sample-default-${stamp}@kestrelridge.co.zw`, demo: undefined },
  { label: 'opt-in', email: `qa-sample-optin-${stamp}@kestrelridge.co.zw`, demo: true },
];
const results = [];

function jar() { return new Map(); }
function capture(res, cookies) {
  const list = typeof res.headers.getSetCookie === 'function'
    ? res.headers.getSetCookie()
    : (res.headers.get('set-cookie') || '').split(/, (?=\S+=)/).filter(Boolean);
  for (const raw of list) {
    const pair = String(raw).split(';')[0];
    const at = pair.indexOf('=');
    if (at > 0) cookies.set(pair.slice(0, at).trim(), pair.slice(at + 1).trim());
  }
}
async function api(pathname, cookies, init = {}) {
  const headers = new Headers(init.headers || {});
  if (cookies.size) headers.set('cookie', [...cookies.entries()].map(([k, v]) => `${k}=${v}`).join('; '));
  if (init.body) headers.set('content-type', 'application/json');
  const res = await fetch(`${BASE}${pathname}`, { ...init, headers, redirect: 'manual', cache: 'no-store' });
  capture(res, cookies);
  const text = await res.text().catch(() => '');
  let body = {};
  try { body = JSON.parse(text); } catch { /* HTML or empty */ }
  return { res, body, text };
}
async function setup(item) {
  const cookies = jar();
  const password = 'SampleDataQA@2026';
  const reg = await api('/api/auth/register', cookies, {
    method: 'POST', body: JSON.stringify({
      name: 'Sample Data QA Owner', email: item.email, password,
      company: `QA Sample Data ${item.label} ${stamp}`,
    }),
  });
  assert.equal(reg.res.status, 200, JSON.stringify(reg.body));
  const org = await api('/api/onboarding', cookies);
  assert.equal(org.res.status, 200, JSON.stringify(org.body));
  const slug = org.body.org?.slug;
  assert.ok(slug, `${item.label}: missing slug`);
  const payload = {
    companyType: 'GENERAL_CONTRACTOR', size: 'MID', headcount: 50,
    name: `QA Sample Data ${item.label} ${stamp}`, legalName: `QA Sample Data ${item.label}`,
    regNumber: `QA/${stamp}`, country: 'ZW', baseCurrency: 'USD',
    qualifiers: [], addons: [],
  };
  if (item.demo !== undefined) payload.loadDemo = item.demo;
  const onboarding = await api('/api/onboarding', cookies, { method: 'POST', body: JSON.stringify(payload) });
  assert.equal(onboarding.res.status, 200, JSON.stringify(onboarding.body));
  assert.equal(onboarding.body.billingStarted, true, `${item.label}: trial did not auto-start`);
  assert.equal(onboarding.body.next, `/${slug}/billing`, `${item.label}: did not return Billing`);
  const { data: orgRow, error } = await admin.from('organizations').select('id').eq('slug', slug).single();
  assert.equal(error?.message || '', '', `${item.label}: organisation lookup failed`);
  const { count, error: countError } = await admin.from('records')
    .select('*', { count: 'exact', head: true }).eq('organization_id', orgRow.id);
  assert.equal(countError?.message || '', '', `${item.label}: record count failed`);
  return { slug, orgId: orgRow.id, recordCount: count || 0 };
}

for (const item of cases) {
  item.result = await setup(item);
  results.push({ label: item.label, ...item.result });
  console.log(`PASS  ${item.label} → ${item.result.slug} · ${item.result.recordCount} records · Billing next`);
}
const [defaultCase, optInCase] = results;
assert.equal(defaultCase.recordCount, 0, 'the default workspace must stay empty');
assert.ok(optInCase.recordCount > 100, 'explicit sample-data opt-in must still seed records');

const wizard = fs.readFileSync('src/components/OnboardingWizard.tsx', 'utf8');
assert.match(wizard, /setLoadDemo\]=useState\(false\)/);
assert.match(wizard, /Off by default/);

const cleanup = `-- Generated by scripts/sample-data-default-qa.mjs\nalter table public.memberships disable trigger memberships_protect_last_owner;\ndelete from public.organizations where slug in ('${defaultCase.slug}','${optInCase.slug}');\ndelete from auth.users where email in ('${cases[0].email}','${cases[1].email}');\nalter table public.memberships enable trigger memberships_protect_last_owner;\nselect (select count(*) from public.organizations where slug in ('${defaultCase.slug}','${optInCase.slug}')) as qa_orgs,\n       (select count(*) from auth.users where email in ('${cases[0].email}','${cases[1].email}')) as qa_users;\n`;
fs.writeFileSync('/home/user/QA_SAMPLE_DATA_CLEANUP.sql', cleanup);
console.log(`\nSample-data QA passed: default ${defaultCase.recordCount} records · opt-in ${optInCase.recordCount} records.`);
console.log('Cleanup SQL: /home/user/QA_SAMPLE_DATA_CLEANUP.sql');
