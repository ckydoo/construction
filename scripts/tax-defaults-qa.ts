import assert from 'node:assert/strict';
import { taxDefault, normaliseTaxSettings } from '../src/lib/tax-settings';
import { CONVERSION_RULES, buildContext } from '../src/lib/conversions';
import { financialTotalsPatch } from '../src/lib/financial';
import { RESOURCE_MAP } from '../src/lib/resources';
assert.equal(taxDefault(undefined), 0);
assert.equal(taxDefault({enabled:false,rate:15}),0);
assert.equal(taxDefault({enabled:true,rate:15}),15);
assert.equal(taxDefault({enabled:true,rate:0}),0);
assert.equal(taxDefault({enabled:true,rate:101}),0);
assert.deepEqual(normaliseTaxSettings({enabled:true,rate:-1}),{enabled:false,rate:0});
for(const id of ['arInvoices','purchaseOrders']) assert.equal(RESOURCE_MAP[id].fields.find(f=>f.key==='vatPct')?.defaultValue,0);
const rule=CONVERSION_RULES.find(r=>r.id==='job-to-invoice')!;
assert.equal(rule.build({id:'p',name:'Job',contractValue:100},buildContext()).vatPct,0);
assert.equal(rule.build({id:'p',name:'Job',contractValue:100},buildContext({enabled:true,rate:12})).vatPct,12);
const lines=[{description:'test',detail:'',qty:1,unitPrice:100,total:100}];
assert.equal(financialTotalsPatch('arInvoices',{vatPct:0},lines).total,100);
assert.equal(financialTotalsPatch('arInvoices',{vatPct:12},lines).total,112);
console.log('Tax defaults unit checks passed; settings/UI/API integration not yet tested.');
