/* Local subscription QA: Stripe test-mode-compatible signed webhooks + Paynow
 * mock. No live keys, no network charge, no production writes. Run against a
 * server started with BILLING_QA_MODE=true PAYNOW_MOCK=true. */
import 'dotenv/config';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const BASE = (process.env.AUDIT_BASE || 'http://127.0.0.1:3000').replace(/\/$/, '');
const QA_SECRET = (process.env.BILLING_QA_SECRET || '').trim();
const CRON_SECRET = (process.env.BILLING_CRON_SECRET || process.env.CRON_SECRET || '').trim();
const ROOT = process.cwd();
const REPORT = path.join(ROOT, 'SUBSCRIPTION_QA_REPORT.md');
const CLEANUP = '/tmp/billing-qa-cleanup.sql';
const stamp = Date.now().toString(36);
const email = `qa-billing-${stamp}@kestrelridge.co.zw`;
const company = `MYLA Billing QA ${stamp}`;
let slug = '';
const jar = new Map();
const results = [];

function capture(res) {
  const list = typeof res.headers.getSetCookie === 'function'
    ? res.headers.getSetCookie()
    : (res.headers.get('set-cookie') || '').split(/, (?=\S+=)/).filter(Boolean);
  for (const raw of list) {
    const pair = String(raw).split(';')[0];
    const at = pair.indexOf('=');
    if (at > 0) jar.set(pair.slice(0, at).trim(), pair.slice(at + 1).trim());
  }
}
function cookieHeader() { return [...jar.entries()].map(([k, v]) => `${k}=${v}`).join('; '); }
async function app(pathname, init = {}) {
  const headers = new Headers(init.headers || {});
  if (jar.size) headers.set('cookie', cookieHeader());
  if (init.body && !headers.has('content-type')) headers.set('content-type', 'application/json');
  const target = /^https?:\/\//.test(pathname) ? pathname : `${BASE}${pathname}`;
  const res = await fetch(target, { ...init, headers, redirect: 'manual' });
  capture(res);
  const text = await res.text();
  let body = text;
  try { body = JSON.parse(text); } catch { /* HTML or empty */ }
  return { res, body, text };
}
function qaHeaders(extra = {}) {
  const h = { 'content-type': 'application/json', ...extra };
  if (QA_SECRET) h['x-myla-qa-secret'] = QA_SECRET;
  return h;
}
async function qa(pathname, body) {
  const res = await fetch(`${BASE}${pathname}`, { method: 'POST', headers: qaHeaders(), body: JSON.stringify(body) });
  const json = await res.json().catch(() => ({}));
  assert.ok(res.ok, `${pathname}: ${JSON.stringify(json)}`);
  return json;
}
async function qaState() {
  const res = await fetch(`${BASE}/api/qa/billing/state?org=${encodeURIComponent(slug)}`, { headers: qaHeaders() });
  const json = await res.json();
  assert.equal(res.status, 200, `QA state: ${JSON.stringify(json)}`);
  return json;
}
async function cron() {
  const headers = {};
  if (CRON_SECRET) headers.authorization = `Bearer ${CRON_SECRET}`;
  const res = await fetch(`${BASE}/api/cron/billing`, { method: 'POST', headers });
  const json = await res.json();
  assert.equal(res.status, 200, `cron: ${JSON.stringify(json)}`);
  return json;
}
function cleanupSql() {
  return `-- Generated by scripts/billing-audit.mjs\n-- Run via Supabase SQL editor / connector on oeadisqfuyhelppinaxw.\nalter table public.memberships disable trigger memberships_protect_last_owner;\ndelete from public.organizations where slug = '${slug}';\ndelete from auth.users where email = '${email}';\nalter table public.memberships enable trigger memberships_protect_last_owner;\nselect (select count(*) from public.organizations where slug = '${slug}') as qa_orgs,\n       (select count(*) from auth.users where email = '${email}') as qa_users;\n`;
}
async function check(name, fn) {
  try {
    const detail = await fn();
    results.push({ name, ok: true, detail: detail || 'PASS' });
    console.log(`PASS  ${name}${detail ? ` — ${detail}` : ''}`);
  } catch (e) {
    results.push({ name, ok: false, detail: e.message });
    console.error(`FAIL  ${name} — ${e.message}`);
    throw e;
  }
}

let failed = false;
try {
  await check('register a new organisation', async () => {
    const r = await app('/api/auth/register', { method: 'POST', body: JSON.stringify({
      name: 'Billing QA Owner', email, password: 'BillingQA@2026', company,
    }) });
    assert.equal(r.res.status, 200, JSON.stringify(r.body));
    slug = r.body.slug;
    assert.ok(slug, 'registration returned a workspace slug');
    return slug;
  });
  await check('onboarding remains reachable before payment', async () => {
    const r = await app('/api/onboarding', { method: 'POST', body: JSON.stringify({
      companyType: 'GENERAL_CONTRACTOR', size: 'MID', headcount: 50,
      name: company, legalName: company, regNumber: `QA/${stamp}`, country: 'ZW',
      baseCurrency: 'USD', qualifiers: [], addons: [], loadDemo: false,
    }) });
    assert.equal(r.res.status, 200, JSON.stringify(r.body));
    return 'onboarded=true';
  });
  await check('billing starts in trial_required with three USD plans', async () => {
    const r = await app(`/api/${slug}/billing`);
    assert.equal(r.res.status, 200, JSON.stringify(r.body));
    assert.equal(r.body.billing.status, 'trial_required');
    assert.equal(r.body.billing.mode, 'qa');
    assert.equal(r.body.billing.canManage, true);
    assert.equal(r.body.billing.plans.length, 3);
    assert.deepEqual(r.body.billing.plans.map((p) => p.priceUsd), [9, 29, 99]);
    return '9 / 29 / 99 USD everywhere';
  });
  await check('hard lock blocks workspace APIs before trial', async () => {
    const r = await app(`/api/${slug}/records/clients`);
    assert.equal(r.res.status, 402);
    assert.equal(r.body.code, 'BILLING_REQUIRED');
    const dashboard = await app(`/${slug}/dashboard`);
    assert.equal(dashboard.res.status, 307);
    assert.match(dashboard.res.headers.get('location') || '', /\/billing$/);
    const billing = await app(`/${slug}/billing`);
    assert.equal(billing.res.status, 200);
    return 'API 402 · dashboard redirects · billing page reachable';
  });
  await check('select Pro and start the 14-day card-required Stripe trial', async () => {
    const plan = await app(`/api/${slug}/billing`, { method: 'POST', body: JSON.stringify({ action: 'selectPlan', planId: 'PRO' }) });
    assert.equal(plan.res.status, 200, JSON.stringify(plan.body));
    const co = await app(`/api/${slug}/billing/checkout`, { method: 'POST', body: JSON.stringify({ planId: 'PRO' }) });
    assert.equal(co.res.status, 200, JSON.stringify(co.body));
    assert.match(co.body.url, /stripe-checkout/);
    const event = await qa('/api/qa/billing/stripe', { orgSlug: slug, step: 'checkout' });
    assert.equal(event.webhookStatus, 200, JSON.stringify(event.result));
    const state = await qaState();
    assert.equal(state.subscription.status, 'trialing');
    assert.equal(state.subscription.plan_id, 'PRO');
    assert.ok(state.subscription.trial_ends_at);
    return 'signed checkout.session.completed → trialing';
  });
  await check('Pro trial grants full write access', async () => {
    const r = await app(`/api/${slug}/records/clients`, { method: 'POST', body: JSON.stringify({ name: 'QA Billing Client' }) });
    assert.equal(r.res.status, 201, JSON.stringify(r.body));
    return 'client record created';
  });
  await check('trial_will_end creates exactly one Paynow invoice and cancels Stripe first', async () => {
    const sw = await app(`/api/${slug}/billing/switch`, { method: 'POST', body: JSON.stringify({ usePaynow: true }) });
    assert.equal(sw.res.status, 200, JSON.stringify(sw.body));
    const e1 = await qa('/api/qa/billing/stripe', { orgSlug: slug, step: 'trial_will_end' });
    assert.equal(e1.webhookStatus, 200, JSON.stringify(e1.result));
    const e2 = await qa('/api/qa/billing/stripe', { orgSlug: slug, step: 'subscription_deleted' });
    assert.equal(e2.webhookStatus, 200, JSON.stringify(e2.result));
    const state = await qaState();
    assert.equal(state.subscription.status, 'switch_pending');
    assert.equal(state.subscription.metadata.switchInitiated, true);
    const pending = state.invoices.filter((i) => i.status === 'pending' && i.gateway !== 'stripe');
    assert.equal(pending.length, 1, 'one Paynow/mock invoice for the first paid period');
    assert.equal(Number(pending[0].amount_usd).toFixed(2), '29.00');
    assert.equal(state.invoices.some((i) => i.gateway === 'stripe' && i.status === 'paid'), false);
    return 'switch_pending · no Stripe charge recorded';
  });
  await check('hash-verified Paynow mock checkout activates the same period', async () => {
    const before = await qaState();
    const pending = before.invoices.find((i) => i.status === 'pending' && i.gateway !== 'stripe');
    assert.ok(pending, 'pending Paynow invoice');
    const pay = await app(`/api/${slug}/billing/pay`, { method: 'POST', body: JSON.stringify({ invoiceId: pending.id }) });
    assert.equal(pay.res.status, 200, JSON.stringify(pay.body));
    assert.match(pay.body.url, /\/api\/webhooks\/paynow\/mock/);
    const redirect = await app(pay.body.url);
    assert.equal(redirect.res.status, 307, `mock checkout redirect: ${redirect.text.slice(0, 200)}`);
    assert.match(redirect.res.headers.get('location') || '', /\/billing/);
    const state = await qaState();
    const paid = state.invoices.find((i) => i.status === 'paid' && i.gateway !== 'stripe');
    assert.ok(paid, 'one paid Paynow invoice');
    assert.equal(state.subscription.status, 'active');
    assert.equal(state.subscription.gateway, 'paynow');
    assert.equal(new Date(state.subscription.current_period_start).toISOString(), new Date(paid.period_start).toISOString());
    assert.ok(state.subscription.last_payment_at);
    return `invoice ${paid.invoice_number} · active until ${paid.period_end.slice(0, 10)}`;
  });
  await check('daily sweep is idempotent', async () => {
    const before = (await qaState()).invoices.length;
    const sweep = await cron();
    assert.equal(sweep.ok, true);
    assert.equal(sweep.renewalInvoices, 0, JSON.stringify(sweep));
    const after = (await qaState()).invoices.length;
    assert.equal(after, before, 'no duplicate invoice');
    return `invoices=${after}`;
  });
  await check('failed renewal gives 3-day grace then hard locks, without deleting data', async () => {
    const failedEvent = await qa('/api/qa/billing/stripe', { orgSlug: slug, step: 'invoice_payment_failed' });
    assert.equal(failedEvent.webhookStatus, 200, JSON.stringify(failedEvent.result));
    let state = await qaState();
    assert.equal(state.subscription.status, 'past_due');
    assert.ok(state.subscription.grace_until);
    await qa('/api/qa/billing/expire', { orgSlug: slug });
    await cron();
    state = await qaState();
    assert.equal(state.subscription.status, 'locked');
    assert.ok(state.recordCount >= 1, 'business data preserved');
    const blocked = await app(`/api/${slug}/records/clients`);
    assert.equal(blocked.res.status, 402);
    const billing = await app(`/api/${slug}/billing`);
    assert.equal(billing.res.status, 200);
    return `locked · ${state.recordCount} record(s) preserved · billing reachable`;
  });
} catch {
  failed = true;
} finally {
  fs.writeFileSync(CLEANUP, cleanupSql());
  const passed = results.filter((r) => r.ok).length;
  const rows = results.map((r) => `| ${r.ok ? 'PASS' : 'FAIL'} | ${r.name} | ${String(r.detail).replace(/\|/g, '\\|')} |`).join('\n');
  fs.writeFileSync(REPORT, `# MYLA subscription shadow QA\n\n**${passed}/${results.length} checks passed** — local mock Stripe signed webhooks + hash-verified Paynow mock against \`${BASE}\`.\n\n| Result | Check | Detail |\n|---|---|---|\n${rows}\n\nWorkspace: \`${slug || 'n/a'}\` · \`${email}\`. No live keys, live charges or production writes were used. Cleanup SQL: \`${CLEANUP}\`.\n`);
  console.log(`\n${passed}/${results.length} checks passed. Report: ${REPORT}`);
  console.log(`Cleanup SQL: ${CLEANUP}`);
  if (failed) process.exit(1);
}
